def looks_like_unfinished_plan(text: str) -> bool:
    """Detect plans and tool calls leaked as plain assistant text, especially for file tasks."""
    value = (text or "").strip()
    if not value:
        return False

    # Some models label the planned file "Plan.md:" rather than writing "Plan:".
    plan_header = re.search(
        r"(?im)^\s*(?:#{1,6}\s*)?(?:plan(?:\.md)?|план)(?:\s*\([^)]*\))?\s*:",
        value,
    ) is not None
    has_checklist = re.search(r"(?im)^\s*\[\s*[x ]?\s*\]\s*\d+[.)]", value) is not None
    start_language = re.search(
        r"(?iu)\b(?:планирую|приступаю|начинаю|начну|я начну|starting|beginning|i(?:'m| am) starting)\b",
        value,
    ) is not None
    step_one = re.search(
        r"(?iu)\b(?:шаг\s*1|step\s*1|первого шага|первый шаг|начинаю с шага 1|starting with step 1)\b",
        value,
    ) is not None
    # Some models print a pseudo-tool call as JSON after ordinary prose, e.g.
    # {"tool_name":"terminal","tool_input":{"command":"curl ..."}}.
    # Detect it anywhere in the output, not only when `terminal:` is the first line.
    tool_preamble = re.search(
        r"(?im)^\s*(?:execute_code|terminal|run_command|tool_call|function_call)\s*:",
        value,
    ) is not None
    pseudo_tool_json = re.search(
        r'(?is)(?:"tool_name"\s*:\s*"(?:execute_code|terminal|run_command|process_manage)"|'
        r'"tool_input"\s*:|"function_call"\s*:|<\|tool_call\|>)',
        value,
    ) is not None
    code_preamble = re.search(r"(?im)^\s*import\s+(?:sys|os|subprocess|pandas)|^\s*from pathlib import import", value) is not None
    return tool_preamble or pseudo_tool_json or (plan_header and (start_language or step_one or has_checklist)) or (has_checklist and start_language) or (code_preamble and start_language)


def build_user_message(text: str, files: list, session) -> str:
    base_url = settings.hermes_callback_base_url.rstrip("/")
    file_lines = []
    for item in files:
        file_url = f"{base_url}/sessions/{session.session_id}/files/{item.id}/content"
        file_lines.append(
            "\n".join(
                [
                    f"Имя: {json.dumps(item.name, ensure_ascii=False)}",
                    f"Размер: {item.size} байт",
                    f"Строк данных: {item.rows}",
                    f"Колонки: {json.dumps(item.columns, ensure_ascii=False)}",
                    f"Типы колонок: {json.dumps(item.column_types, ensure_ascii=False)}",
                    f"URL для скачивания: {file_url}",
                ]
            )
        )
    parts = [f"Задача пользователя: {json.dumps(text, ensure_ascii=False)}"]
    if file_lines:
        parts.extend(["", "Входные файлы:", *file_lines])
    parts.extend(
        [
            "",
            "Правило доступа к вложениям: скачивай входные файлы только инструментом terminal, не через execute_code. Используй curl.exe. После скачивания проверь, что локальный файл существует и имеет ожидаемый ненулевой размер. Если terminal отсутствует или URL недоступен из его среды, сообщи конкретный сбой и не проси повторную загрузку файла.",
            f"X-Hermes-Task-Token: {session.tool_token}",
            f"Endpoint загрузки готовых файлов: {base_url}/sessions/{session.session_id}/artifacts",
            "Загружай только файлы, которые созданы для результата этой задачи. Используй простые имена файлов латиницей с подчёркиваниями, без пробелов и каталогов.",
        ]
    )
    return "\n".join(parts)
